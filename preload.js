  addModrinthMod: (p) => ipcRenderer.invoke('omods:addModrinth', p),
  addLocalMod: (p) => ipcRenderer.invoke('omods:addLocal', p),
  listShaders: () => ipcRenderer.invoke('shaders:list'),
  searchShaders: (q) => ipcRenderer.invoke('shaders:search', q),
  addShader: (p) => ipcRenderer.invoke('shaders:add', p),
  removeShader: (f) => ipcRenderer.invoke('shaders:remove', f),
  openShaderFolder: () => ipcRenderer.invoke('shaders:folder'),
  discordStatus: () => ipcRenderer.invoke('discord:status'),
  newsList: () => ipcRenderer.invoke('news:list'),
  submitShot: (p) => ipcRenderer.invoke('gallery:submit', p),
  featuredGallery: () => ipcRenderer.invoke('gallery:featured'),
  voteShot: (p) => ipcRenderer.invoke('gallery:vote', p),
  authState: () => ipcRenderer.invoke('auth:state'),
  authLogin: (p) => ipcRenderer.invoke('auth:login', p),
  authRegister: (p) => ipcRenderer.invoke('auth:register', p),
  authLogout: () => ipcRenderer.invoke('auth:logout'),
  friendsList: () => ipcRenderer.invoke('friends:list'),
  friendRequest: (to) => ipcRenderer.invoke('friends:request', to),
  friendRespond: (p) => ipcRenderer.invoke('friends:respond', p),
