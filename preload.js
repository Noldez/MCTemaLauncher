  chatTyping: (p) => ipcRenderer.invoke('chat:typing', p),
  chatSendImage: (p) => ipcRenderer.invoke('chat:sendImage', p),
  groupCreate: (p) => ipcRenderer.invoke('groups:create', p),
  groupAddMember: (p) => ipcRenderer.invoke('groups:addMember', p),
